# Несколько вопросов / два источника: часть вопросов или один из источников может быть пуст,
# поэтому «ответь ровно NO_CONTEXT» здесь не подходит — отказ даётся по каждому пункту отдельно.
USER_PROMPT_TEMPLATE_PARTIAL = """{mode_instruction}

Контекст:
{context}

Вопрос: {question}

Напоминание: используй ТОЛЬКО контекст выше; чего в нём нет — прямо так и напиши по этому пункту, не угадывай."""

# --- Проверочный проход (groundedness) — см. app/verification/verify.py -----

CORRECTION_TEMPLATE = """{mode_instruction}

Контекст из {source_label}:
{context}

Вопрос студента: {question}

Твой предыдущий ответ содержал утверждения, которых НЕТ в контексте:
{issues}

Перепиши ответ, оставив ТОЛЬКО то, что напрямую подтверждается контекстом выше. \
Если после удаления неподтверждённого не остаётся содержательного ответа — выведи ровно "{no_context_answer}"."""

CONSPECT_PATTERN = re.compile(
    r"конспект|кратко разбери|структурируй|выпиши основное|сделай схему|схему для тетради|"
    r"быстро повторить|структуру вопроса",
    re.IGNORECASE,
)
EXPLANATION_PATTERN = re.compile(
    r"объясни|простыми словами|по-простому|на пальцах|аналоги", re.IGNORECASE
)


def detect_mode(question: str) -> Literal["question", "conspect", "explanation"]:
    if CONSPECT_PATTERN.search(question):
        return "conspect"
    if EXPLANATION_PATTERN.search(question):
        return "explanation"
    return "question"


def _format_source(chunk: ChunkResult) -> str:
    # У клинреков автора нет (author пустой) — источником служит название рекомендации.
    head = f"{chunk.author}, {chunk.title}" if chunk.author else chunk.title
    if chunk.page_from is None:
        return head
    if chunk.page_from == chunk.page_to:
        return f"{head}, стр. {chunk.page_from}"
    return f"{head}, стр. {chunk.page_from}-{chunk.page_to}"


def build_context(chunks: list[ChunkResult], threshold: float | None = None) -> str:
    relevant = relevant_chunks(chunks, threshold)
    if not relevant:
        return NO_CONTEXT_PLACEHOLDER
    return "\n---\n".join(f"[{_format_source(c)}]\n{c.content}" for c in relevant)


def detect_subject(chunks: list[ChunkResult], threshold: float | None = None) -> str | None:
    relevant = relevant_chunks(chunks, threshold)
    if not relevant:
        return None
    return Counter(c.subject for c in relevant).most_common(1)[0][0]


async def _complete(
    system_prompt: str,
    user_prompt: str,
    temperature: float,
    task: Task = Task.GROUNDED_QA,
    history: list[dict] | None = None,
) -> str:
    text, _truncated = await _complete_ex(system_prompt, user_prompt, temperature, task, history)
    return text


async def _complete_ex(
    system_prompt: str,
    user_prompt: str,
    temperature: float,
    task: Task = Task.GROUNDED_QA,
    history: list[dict] | None = None,
) -> tuple[str, bool]:
    """Вызов модели через общий слой провайдеров; второй элемент — ответ упёрся в лимит
    токенов (текст уже обрезан по последнему законченному предложению).

    Модель не задаётся здесь: её определяет TaskModelMap по атомарной задаче
    (§56.5 ТЗ), а слой провайдера сохраняет расход по каждому вызову (§59).
    """
    messages = [{"role": "system", "content": system_prompt}]
    if history:
        messages.extend(history)
    messages.append({"role": "user", "content": user_prompt})
    try:
        result = await llm.complete(task, messages, temperature=temperature)
    except llm.LLMError as e:
        raise RuntimeError(llm.PROVIDER_ERROR_MESSAGE) from e
    if result.truncated:
        return trim_to_sentence(result.text), True
    return result.text, False


def trim_to_sentence(text: str) -> str:
    """Ответ упёрся в лимит токенов: режем по последнему законченному предложению/
    строке, чтобы студент не видел обрыв на полуслове и висящий `**`. Если законченной
    границы нет в хвосте (последние 60%) — оставляем как есть, не выбрасывая ответ."""
    cut = max(text.rfind(ch) for ch in (".", "!", "?", "…", "\n"))
    if cut < int(len(text) * 0.4):
        return text
    return text[: cut + 1].rstrip()


@dataclass
class GeneratedAnswer:
    text: str
    # True — прошёл проверку (Verification Layer). False — не прошёл даже после
    # корректирующей перегенерации, текст уже заменён на честный отказ (§15).
    # None — верификация не выполнялась (VERIFY_GROUNDING=False) или сам
    # верификатор был недоступен (§36) — ответ не помечается verified.
    verified: bool | None
    # Ответ упёрся в лимит токенов и был обрезан по законченному предложению —
    # app/workflows/dialog.py дописывает «продолжу с этого места» вместо видимого обрыва.
    truncated: bool = False


async def _verify_and_repair(
    context: str,
    answer: str,
    correct: Callable[[str], Awaitable[str]],
    *,
    always_check: bool = True,
) -> GeneratedAnswer:
    """Общий цикл Verification Layer для generate_answer/_reasoning_answer
    (app/verification/verify.py): PASS сразу; при проблеме — один корректирующий
    проход (`correct(issues)`) и повторная проверка; если проблема осталась —
    честный отказ вместо недостоверного ответа, а не молчаливая выдача как есть.

    Батч 19: проверка — отдельный LLM-вызов на весь контекст, самая долгая часть
    после генерации. `always_check=False` (обычный учебный ответ) пропускает её,
    если в ответе нет чисел с единицами (дозы, проценты, сроки) — тогда verified=None
    («не проверялся»), а не ложное «проверен».
    """
    if not settings.VERIFY_GROUNDING:
        return GeneratedAnswer(answer, verified=None)
    if not always_check and not extract_numeric_claims(answer):
        return GeneratedAnswer(answer, verified=None)

    result = await verify_answer(context, answer)
    if result.grounded is True:
        return GeneratedAnswer(answer, verified=True)
    if result.grounded is None:
        return GeneratedAnswer(answer, verified=None)

    logger.info("Ответ не прошёл проверку, перегенерирую. Проблемы: %s", result.issues)
    corrected = await correct(result.issues)

    result2 = await verify_answer(context, corrected)
    if result2.grounded is True:
        return GeneratedAnswer(corrected, verified=True)
    if result2.grounded is None:
        return GeneratedAnswer(corrected, verified=None)

    logger.info("Исправленный ответ снова не прошёл проверку — честный отказ вместо недостоверного ответа")
    return GeneratedAnswer(NO_CONTEXT_ANSWER, verified=False)


async def generate_answer(
    question: str,
    chunks: list[ChunkResult],
    source_type: str = SOURCE_TEXTBOOK,
    history: list[dict] | None = None,
    task: Task = Task.GROUNDED_QA,
    dialog: bool = False,
    mode_override: str | None = None,
) -> GeneratedAnswer:
    """Генерирует ответ с учётом режима.

    `mode_override` — готовая инструкция режима (несколько вопросов, батч 27); заменяет
    выбор режима по задаче/тексту вопроса.

    `dialog=True` (Telegram/админка) — режим «полно по крупным разделам + вопрос в конце»;
    False (сайт, /v1) — один максимально полный ответ без деления и без вопроса.

    - source_type='клинрек' — врачебный клинический промпт (глубоко, из одной рекомендации).
    - source_type='учебник' — студенческий промпт (как для экзамена), либо EXPLAIN/CLASS_QUICK
      (§24, §53.1 ТЗ), если так классифицировал Orchestrator (app/orchestration/router.py) —
      `task` определяет и модель через TaskModelMap, и стиль ответа.
    Если в материалах релевантного нет — гибкий фолбэк: приветствие или ответ из общих
    знаний ИИ с ОБЯЗАТЕЛЬНОЙ пометкой, что это не из загруженных материалов.
    """
    is_clinrek = source_type == SOURCE_CLINREK
    if is_clinrek:
        source_label = "клинических рекомендаций"
    elif task is Task.DOCUMENT_QA:
        source_label = "личного документа"
    else:
        source_label = "учебников"
    # Личный документ: порог релевантности мягче, чем у учебников (конспект пишут сжато).
    threshold = document_threshold() if task is Task.DOCUMENT_QA else None
    context = build_context(chunks, threshold)

    # Материалов по вопросу нет: либо приветствие/small talk, либо общий вопрос —
    # уводим в гибкий фолбэк (общие знания с честной пометкой). Верификация не нужна.
    if context == NO_CONTEXT_PLACEHOLDER:
        fallback_prompt = await get_prompt("FALLBACK_SYSTEM_PROMPT", FALLBACK_SYSTEM_PROMPT)
        answer = await _complete(
            fallback_prompt,
            FALLBACK_USER_TEMPLATE.format(question=question),
            GENERATION_TEMPERATURE,
            history=history,
        )
        return GeneratedAnswer(answer, verified=None)

    if is_clinrek:
        system_prompt = await get_prompt("CLINREK_SYSTEM_PROMPT", CLINREK_SYSTEM_PROMPT)
    else:
        system_prompt = await get_prompt("SYSTEM_PROMPT", SYSTEM_PROMPT)
        # Universal Core + Subject Profile: профиль по предмету найденных чанков.
        # Нет профиля у предмета («other», документ студента) — ядро как есть.
        subject = detect_subject(chunks, threshold)
        default_profile = default_profile_text(subject) if subject else None
        if default_profile is not None:
            profile = await get_prompt(profile_key(subject), default_profile)
            system_prompt = f"{system_prompt}\n\n{profile}"

    if mode_override is not None:
        mode_instruction = mode_override
    elif is_clinrek:
        mode_instruction = clinrek_mode_instruction(question, dialog)
    elif task is Task.EXPLAIN:
        mode_instruction = f"{EXPLAIN_MODE_INSTRUCTION}\n\n{full_mode_instruction(question, dialog)}"
    elif task is Task.CLASS_QUICK:
        mode_instruction = CLASS_QUICK_MODE_INSTRUCTION
    elif task is Task.TEST_SOLVE_TEXT:
        mode_instruction = TEST_SOLVE_MODE_INSTRUCTION
    elif task is Task.DOCUMENT_QA:
        mode_instruction = f"{DOCUMENT_QA_MODE_INSTRUCTION}\n\n{full_mode_instruction(question, dialog)}"
    else:
        mode = detect_mode(question)
        if mode == "question":
            mode_instruction = full_mode_instruction(question, dialog)
        elif mode == "explanation":
            mode_instruction = f"{MODE_INSTRUCTIONS[mode]}\n\n{full_mode_instruction(question, dialog)}"
        else:
            mode_instruction = MODE_INSTRUCTIONS[mode]

    if mode_override is not None:
        user_prompt = USER_PROMPT_TEMPLATE_PARTIAL.format(
            mode_instruction=mode_instruction, context=context, question=question
        )
    else:
        user_prompt = USER_PROMPT_TEMPLATE.format(
            mode_instruction=mode_instruction,
            source_label=source_label,
            context=context,
            question=question,
            no_context_answer=NO_CONTEXT_ANSWER,
        )

    answer, truncated = await _complete_ex(system_prompt, user_prompt, GENERATION_TEMPERATURE, task, history)
    state = {"truncated": truncated}

    async def correct(issues: str) -> str:
        correction_prompt = CORRECTION_TEMPLATE.format(
            mode_instruction=mode_instruction,
            source_label=source_label,
            context=context,
            question=question,
            issues=issues,
            no_context_answer=NO_CONTEXT_ANSWER,
        )
        corrected, state["truncated"] = await _complete_ex(
            system_prompt, correction_prompt, GENERATION_TEMPERATURE, task, history
        )
        return corrected

    result = await _verify_and_repair(context, answer, correct, always_check=is_clinrek)
    result.truncated = state["truncated"] and result.verified is not False
    return result


async def generate_combined(
    question: str,
    doc_chunks: list[ChunkResult],
    book_chunks: list[ChunkResult],
    history: list[dict] | None = None,
    dialog: bool = False,
    mode_override: str | None = None,
) -> GeneratedAnswer:
    """Смешанный режим (батч 27): ОДИН вызов модели с двумя размеченными блоками контекста
    (документ студента / учебники) — дешевле двух вызовов, а ответ строго разделён
    на «📄 Из твоего документа» и «📚 Из учебников»."""
    doc_relevant = relevant_chunks(doc_chunks, document_threshold())
    book_relevant = relevant_chunks(book_chunks)
    if not doc_relevant and not book_relevant:
        return GeneratedAnswer(NO_CONTEXT_ANSWER, verified=None)

    def block(chunks: list[ChunkResult]) -> str:
        if not chunks:
            return "(по этому вопросу в этом источнике ничего не найдено)"
        return "\n---\n".join(f"[{_format_source(c)}]\n{c.content}" for c in chunks)

    context = (
        "=== 📄 ДОКУМЕНТ СТУДЕНТА ===\n" + block(doc_relevant)
        + "\n\n=== 📚 УЧЕБНИКИ ===\n" + block(book_relevant)
    )
    base = await get_prompt("SYSTEM_PROMPT", SYSTEM_PROMPT)
    instruction = (
        mode_override
        if mode_override is not None
        else f"{COMBINED_MODE_INSTRUCTION}\n\n{full_mode_instruction(question, dialog)}"
    )
    user_prompt = USER_PROMPT_TEMPLATE_PARTIAL.format(
        mode_instruction=instruction, context=context, question=question
    )
    answer, truncated = await _complete_ex(base, user_prompt, GENERATION_TEMPERATURE, Task.GROUNDED_QA, history)

    async def correct(issues: str) -> str:
        fixed, _t = await _complete_ex(
            base,
            user_prompt + "\n\nУбери из ответа все утверждения, которых нет в контексте. Проблемы:\n" + issues,
            GENERATION_TEMPERATURE,
            Task.GROUNDED_QA,
            history,
        )
        return fixed

    result = await _verify_and_repair(context, answer, correct, always_check=False)
    result.truncated = truncated and result.verified is not False
    return result


EXPAND_SYSTEM_PROMPT = """Тебе дан вопрос студента по его личному документу (конспект, лекция). Дай до 3 РАЗНЫХ поисковых формулировок для поиска по документу: (1) вопрос своими словами, (2) ключевые медицинские термины/названия, включая латинские и сокращения, (3) синонимы и смежные понятия, под которыми это могло быть записано. Ничего не выдумывай — только переформулировки того, о чём спросили.
Верни ТОЛЬКО JSON: {"queries": ["...", "..."]}"""


async def expand_queries(question: str, turns: list[tuple[str, str]] | None = None) -> list[str]:
    """Несколько формулировок поиска для личного документа (батч 27): буквальный поиск по
    словам вопроса пропускал места, записанные другими словами. Один дешёвый вызов
    (Task.QUERY_REWRITE); при любом сбое — исходный вопрос, поиск не ломается."""
    context = ""
    if turns:
        context = "Контекст диалога:\n" + "\n".join(f"Вопрос: {q}" for q, _a in turns[-2:]) + "\n\n"
    try:
        result = await llm.complete(
            Task.QUERY_REWRITE,
            [
                {"role": "system", "content": EXPAND_SYSTEM_PROMPT},
                {"role": "user", "content": f"{context}Вопрос: {question}"},
            ],
            temperature=0.0,
            max_output_tokens=300,
            json_schema={"required": ["queries"]},
        )
    except llm.LLMError:
        return [question]
    raw = (result.data or {}).get("queries")
    extra = [q.strip() for q in raw if isinstance(q, str) and q.strip()] if isinstance(raw, list) else []
    queries = [question]
    for q in extra:
        if q.lower() != question.lower() and q not in queries and len(q) <= 300:
            queries.append(q)
    return queries[:4]


async def _reasoning_answer(
    system_prompt: str,
    question: str,
    chunks: list[ChunkResult],
    source_type: str,
    history: list[dict] | None = None,
) -> GeneratedAnswer | None:
    """Заземлённый клинический разбор (дифдиагноз/сочетание). Возвращает None, если
    релевантных материалов нет — тогда вызывающий спросит согласие на общие знания."""
    context = build_context(chunks)
    if context == NO_CONTEXT_PLACEHOLDER:
        return None

    user_prompt = REASONING_USER_TEMPLATE.format(context=context, question=question)
    answer = await _complete(
        system_prompt, user_prompt, GENERATION_TEMPERATURE, Task.GROUNDED_QA, history
    )

    async def correct(issues: str) -> str:
        correction = user_prompt + (
            "\n\nВАЖНО: убери из ответа ВСЕ утверждения, которых нет в контексте выше "
            "(медицина — выдумки недопустимы). Проблемные места:\n" + issues
        )
        return await _complete(
            system_prompt, correction, GENERATION_TEMPERATURE, Task.GROUNDED_QA, history
        )

    return await _verify_and_repair(context, answer, correct)


