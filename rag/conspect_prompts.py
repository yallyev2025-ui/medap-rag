def conspect_subject_key(subject: str) -> str:
    return f"CONSPECT_SUBJECT_{subject}"


def default_conspect_subject_text(subject: str) -> str | None:
    entry = CONSPECT_SUBJECTS.get(subject)
    if entry is None:
        return None
    name, body = entry
    return f"ПРЕДМЕТ: {name}. {body}"


_PLACEHOLDER = re.compile(r"\{(topic|fragments)\}")


def fill_prompt(template: str, topic: str, fragments: str) -> str:
    """Подставляет {topic} и {fragments} за один проход (текст фрагмента не может сам
    оказаться шаблоном: str.format падал бы на фигурных скобках учебников)."""
    values = {"topic": topic, "fragments": fragments}
    return _PLACEHOLDER.sub(lambda m: values[m.group(1)], template)
