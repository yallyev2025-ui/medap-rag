"""Мелкие текстовые помощники исследования: сравнение слов и разбор вопроса.

Отдельный модуль, а не импорт из `bot/fragments.py`: тот живёт в Telegram-слое и
знает про разметку сообщений. Здесь нужны только сравнения «этот кусок про этот
пункт или нет» — без HTML и без клавиатур.

Сравнение слов — по «скелету»: согласные плюс первая буква. Русские окончания
меняют гласные, но не согласные: «ядра», «ядер», «ядро» дают один скелет «ядр»,
«функции» и «функция» — «фнкц», «лечение» и «лечения» — «лчн». Это дешевле и
предсказуемее словаря: без внешних зависимостей и без загрузки морфологии в
память боевого сервера. Скелет грубее настоящей леммы (у «лечить» он другой),
поэтому совпадением считается и общее начало скелетов.
"""

import re

_WORD = re.compile(r"[\w-]+", flags=re.UNICODE)

_VOWELS = set("аеёиоуыэюяaeiouy")
_SIGNS = set("ьъй")

# Служебные слова, которые есть в любом вопросе и ни о чём не говорят. Список
# намеренно короткий и общий: это не медицинский шаблон, а шум формулировки.
_STOP = {
    "что", "такое", "как", "какие", "какой", "какая", "каков", "чем", "это",
    "для", "при", "про", "или", "если", "есть", "быть", "было", "были", "был",
    "его", "её", "ее", "их", "они", "она", "оно", "мы", "вы", "мне", "меня",
    "все", "всё", "всем", "всех", "весь", "вся", "также", "ещё", "еще", "уже",
    "можно", "нужно", "надо", "дай", "дайте", "скажи", "расскажи", "объясни",
    "подробно", "полный", "полное", "полностью", "кратко", "коротко",
    "опиши", "перечисли", "напиши", "составь", "сделай", "покажи",
    "пожалуйста", "самый", "самые", "более", "менее", "очень", "тоже",
    "который", "которая", "которые", "которых", "котором", "где", "когда",
    "почему", "зачем", "сколько", "ли", "же", "бы", "не", "ни", "но", "и",
    "в", "во", "на", "с", "со", "к", "ко", "о", "об", "обо", "от", "до",
    "по", "из", "за", "над", "под", "без", "у", "а", "то", "том", "этот",
    "эта", "эти", "того", "тому", "тем", "них", "ним", "ней", "нём", "нем",
    "каждый", "каждого", "каждой", "каждые", "всего", "именно", "также",
    "главное", "основные", "основное", "краткий", "подробный",
}

MIN_SKELETON = 3


def words(text: str) -> list[str]:
    return _WORD.findall((text or "").lower())


def _skeleton(word: str) -> str:
    """Согласные слова плюс первая буква. «ядра» → «ядр», «функций» → «фнкц»."""
    if not word:
        return ""
    head = word[0]
    tail = "".join(ch for ch in word[1:] if ch not in _VOWELS and ch not in _SIGNS)
    return head + tail


def stems(text: str) -> set[str]:
    """Скелеты слов текста без служебных слов. Грубо, но бесплатно и без словарей."""
    found: set[str] = set()
    for word in words(text):
        if len(word) < 3 or word in _STOP:
            continue
        skeleton = _skeleton(word)
        if len(skeleton) >= MIN_SKELETON:
            found.add(skeleton)
    return found


def meaningful_words(text: str) -> list[str]:
    return [w for w in words(text) if len(w) >= 3 and w not in _STOP]


def has_partial_match(stem: str, chunk_stems: set[str]) -> bool:
    """Есть ли слово с этим скелетом среди скелетов куска.

    Совпадение точное или по началу: «ядр» и «ядрн» (ядерный) — одно и то же
    слово в разных формах, а «леч» и «лчн» — уже разные скелеты и не сходятся.
    Начало сравнивается только у достаточно длинных скелетов, иначе «пт» и
    «птх» (пот/патология) склеились бы зря.
    """
    if stem in chunk_stems:
        return True
    for other in chunk_stems:
        short, long_ = (stem, other) if len(stem) <= len(other) else (other, stem)
        if len(short) >= 4 and long_.startswith(short):
            return True
    return False