"""Что прислал студент: тестовые вопросы с вариантами или список экзаменационных вопросов.

Нумерованный список из двух и более пунктов раньше всегда шёл в режим «несколько вопросов»:
один короткий ответ на каждый (1–2 предложения), по 3 фрагмента на вопрос. Для тестов с
вариантами это верно. Для списка экзаменационных вопросов («1. Понятие о химиотерапии…
2. Принципы рациональной химиотерапии») — нет: по каждому нужен полный структурированный
ответ, как на одиночный вопрос (владелец 07.10.2026: получился сплошной текст, часть вопроса
«в материалах не найдено»). Модуль без зависимостей, чтобы проверяться отдельно.
"""

import re

# Вариант ответа: «а) …», «б. …», «A) …», «1) …» в начале строки или после пробела
_OPTION = re.compile(r"(?:^|\s)(?:[а-дa-eА-ДA-E])\s*[).]\s+\S")

# Столько экзаменационных вопросов отвечаются полно, каждый отдельной генерацией; больше —
# прежний компактный режим (иначе одно сообщение стоило бы десятки вызовов модели)
MAX_OPEN_QUESTIONS = 8


def has_options(item: str) -> bool:
    """В вопросе есть варианты ответа: отдельные строки или два и более «а) … б) …» подряд."""
    if "\n" in item.strip():
        return True
    return len(_OPTION.findall(item)) >= 2


def is_open_exam_list(items: list[str]) -> bool:
    """Список вопросов без вариантов ответа: каждый требует развёрнутого ответа."""
    return 2 <= len(items) <= MAX_OPEN_QUESTIONS and not any(has_options(i) for i in items)
