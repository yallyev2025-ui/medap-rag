async def rotate_status(
    set_status: Callable[[str], Awaitable[None]], interval: float = 5.5
) -> None:
    """Раз в `interval` секунд меняет текст статус-сообщения. Отменяется снаружи."""
    order = random.sample(PHRASES, len(PHRASES))
    index = 0
    while True:
        await asyncio.sleep(interval)
        await set_status(order[index % len(order)])
        index += 1
