async def rotate_status(
    set_status: Callable[[str], Awaitable[None]],
    interval: float = 5.5,
    user_key: str | int | None = None,
    pools: Iterable[str] = ("general", "medicine"),
) -> None:
    """Меняет текст статус-сообщения, пока готовится ответ. Отменяется снаружи.

    Сначала короткая служебная строка, потом по кругу лайфхак, история (по частям), факт и снова служебная строка.
    `user_key` — кто ждёт: по нему помнится, что уже показано (без ключа — как у нового человека каждый раз).
    """
    key = str(user_key) if user_key is not None else f"anon-{random.random()}"
    pool_list = list(pools)
    n = 0
    await asyncio.sleep(interval)
    while True:
        if n % 4 == 0:
            await set_status(next_line(key, PHRASES))
            await asyncio.sleep(interval)
        else:
            shown = next_item(key, pool_list)
            await set_status(shown.text)
            await asyncio.sleep(shown.seconds)
        n += 1
